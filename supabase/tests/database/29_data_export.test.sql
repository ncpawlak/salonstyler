  $$select c.relname::text from pg_class c
     where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p')
       and exists (select 1 from pg_attribute a where a.attrelid = c.oid
                    and a.attname = 'salon_id' and not a.attisdropped)
       and c.relname::text not in (select table_name from private.data_export_tables)$$,
  'every salon-owned table is registered for export or explicitly excluded (see supabase/docs/data-export.md)');

select is_empty(
  $$select table_name from private.data_export_tables where note is null and not included$$,
  'every exclusion says why');

select is(
  (select count(*)::int from unnest(private.data_export_order())),
  (select count(*)::int from private.data_export_tables where included),
  'every exported table has a place in the insert order (no FK cycle)');

select is_empty(
  $$select child.relname::text || ' -> ' || parent.relname::text
      from pg_constraint c
      join pg_class child on child.oid = c.conrelid
      join pg_class parent on parent.oid = c.confrelid
     where c.contype = 'f' and child.oid <> parent.oid
       and child.relname::text = any (private.data_export_order())
       and parent.relname::text = any (private.data_export_order())
       and array_position(private.data_export_order(), parent.relname::text)
           > array_position(private.data_export_order(), child.relname::text)$$,
  'parents come before children in the insert order');

select is_empty(
  $$select r.table_name || '.' || s.col
      from private.data_export_tables r, unnest(r.secret_columns) s(col)
      join information_schema.columns c on c.column_name = s.col
     where c.table_schema = 'public' and c.table_name = r.table_name
       and c.column_default is null and c.is_nullable = 'NO'$$,
  'every secret column is regenerated by a default on import');

