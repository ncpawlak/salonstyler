/**
 * Writes `src/assistant/tools/index.ts`, which imports every tool file in that folder. Adding a
 * tool means adding one file and running `npm run gen:tools -w @chairside/ai`; no shared list
 * to edit by hand. A test fails if the index is stale.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

export const TOOLS_DIR = join(dirname(fileURLToPath(import.meta.url)), '../src/assistant/tools');
export const INDEX_FILE = join(TOOLS_DIR, 'index.ts');

export const listToolFiles = (dir = TOOLS_DIR) =>
  readdirSync(dir)
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts' && !f.endsWith('.test.ts'))
    .sort();

const toIdentifier = (file: string) =>
  file.replace(/\.ts$/, '').replace(/[-_.]+([a-z0-9])/gi, (_, c: string) => c.toUpperCase()) +
  'Tool';

export async function renderToolIndex(files: string[] = listToolFiles()): Promise<string> {
  const ids = files.map(toIdentifier);
  const source = [
    '// Generated by `npm run gen:tools -w @chairside/ai`. Do not edit: add or remove a file in',
    '// this folder and re-run it. On a merge conflict, take either side and re-run.',
    ...files.map((f, i) => `import ${ids[i]} from './${f}';`),
    '',
    '/** Every assistant tool, in file order. `tools.ts` sorts them by `order` for the model. */',
    `export const TOOL_MODULES = [\n${ids.map((id) => `  ${id},`).join('\n')}\n] as const;`,
    '',
  ].join('\n');
  const config = (await resolveConfig(INDEX_FILE)) ?? {};
  return format(source, { ...config, filepath: INDEX_FILE });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(INDEX_FILE, await renderToolIndex());
  console.log(`Wrote ${INDEX_FILE}`);
}
